import { unstable_cache } from 'next/cache';

/**
 * Кэширование публичного слоя.
 *
 * Компромисс зафиксирован осознанно: данные публичных страниц живут в кэше минуту,
 * поэтому после снятия курса с публикации страница отдаётся ещё примерно столько же.
 * Сам API закрывает доступ сразу. Точнее — до срока кэша плюс один запрос: Next отдаёт
 * просроченное значение и обновляет его в фоне, поэтому 404 приходит со второго запроса.
 *
 * Здесь два разных грабель, оба проверены на живой сборке.
 *
 * 1. Обычный fetch-кэш не годится: Next не сохраняет неуспешные ответы. Ревалидация
 *    получала бы 404, Next отбрасывал бы его и продолжал отдавать последний успешный —
 *    снятый курс жил бы бесконечно. `unstable_cache` кэширует возвращаемое значение
 *    функции, включая `null`, поэтому «недоступно» тоже истекает по сроку.
 *
 * 2. `export const revalidate` на странице ставить нельзя по той же причине: если рендер
 *    уходит в `notFound()`, Next оставляет прошлый удачный HTML. Страницы рендерятся
 *    на каждый запрос — это дёшево, потому что данные уже в кэше. Сверяет cache.test.ts.
 *
 * Каталог, подборки и постраничная выдача карточек не кэшируются: у каталога слишком
 * много комбинаций фильтров, подборки проверяют доступность оригиналов на каждый запрос,
 * карточки сверяют revision.
 */
export const PUBLIC_REVALIDATE_SECONDS = 60;

/** Загрузчик публичных данных: `null` означает «недоступно» и тоже кэшируется. */
export function cachedPublicRead<A extends unknown[], T>(
  keyParts: string[],
  load: (...args: A) => Promise<T>,
): (...args: A) => Promise<T> {
  return unstable_cache(load, keyParts, { revalidate: PUBLIC_REVALIDATE_SECONDS });
}
